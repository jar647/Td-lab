const assert = require('node:assert/strict');
const app = require('./ufc_app.js');
const research = require('./ufc_research_engine.js');
assert.equal(app.tier({notes:[{headline:'Early Prelims'}]}),'early');
assert.equal(app.tier({notes:{headline:'Prelims'}}),'prelim');
assert.equal(app.tier({type:{text:'Main Card'}}),'main');
assert.equal(app.tier({type:{abbreviation:'Heavyweight'}}),'unknown');
assert.equal(app.nameKey('  José  Souza '),app.nameKey('Jose Souza'));
for(const v of ['', ' ', null, undefined, false, true, {}, [], 'abc', 99, -99, 0, 100.5, Infinity])assert.equal(app.implied(v),null);
assert.equal(app.implied('-100'),0.5);
assert.equal(app.implied('+100'),0.5);
const m = app.market(-125,105);
assert.ok(Math.abs(m.fair[0]+m.fair[1]-1)<1e-10);
assert.ok(m.margin>0);
assert.ok(app.market(150,150).margin<0);
assert.equal(app.market('-125',''),null);
const percent = app.statsFrom({statistics:[{name:'significantStrikeAccuracy',value:0.48,displayValue:'48%'}]});
assert.equal(percent.strAcc,48);
assert.equal(app.statsFrom({statistics:{strAcc:0.48}}).strAcc,48);
assert.equal(app.statsFrom({statistics:{strAcc:'48%'}}).strAcc,48);
assert.equal(app.statsFrom({statistics:{strAcc:48}}).strAcc,48);
assert.equal(percent.slpm,null);
const valid={id:'1',date:'2026-11-07T22:00Z',competitions:[{}]};
assert.equal(app.eventsFrom({events:[valid,valid,{id:'2',date:'bad',competitions:[{}]},{id:'3',date:valid.date,competitions:[]}]}).length,1);
assert.throws(()=>app.eventsFrom({bad:[]}));
assert.match(app.scheduleUrl(new Date('2026-01-03T00:00Z')),/dates=20251227-20260214/);
assert.equal(app.escape('<img onerror="x">'), '&lt;img onerror=&quot;x&quot;&gt;');
const base={slpm:4.2,sapm:3.1,strAcc:48,strDef:55,tdAvg:1.8,tdAcc:42,tdDef:72,subAvg:0.4};
for(const value of [true,false,' ',[],{}])assert.equal(research.evaluate({...base,slpm:value},base).status,'insufficient_data');
console.log('UFC card classification, odds, data normalization and model input tests PASS');
