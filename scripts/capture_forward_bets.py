"""Freeze pregame TD LAB decisions only with explicit, independently verified identity mapping.

Mappings are NOT generated by name similarity. Each verified link must specify
fixture_id, player_id, sportsbook player_name, season, week, and both NFL teams.
Absent verified links, no decisions are emitted. No historical backfilling.
"""
import datetime as dt
import json
from pathlib import Path
from scripts.calibrate_td import score_to_bucket

ROOT = Path("data")
MAPPINGS = ROOT / "verified_fixture_players.json"
OUT = ROOT / "forward/decisions"

def parse(value):
    x = dt.datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    if x.tzinfo is None:
        raise ValueError("Timezone missing")
    return x.astimezone(dt.timezone.utc)

def rank(p):
    def cap(k, den):
        return min(1, max(0, float(p.get(k, 0)) / den))
    raw = 100 * (.35 * cap("tdallowed", 1.5) + .20 * cap("rzallowed", 4)
                 + .25 * cap("rzshare", 50) + .20 * cap("playerRz", 2.5))
    return int(raw * (.65 + .35 * min(1, float(p.get("games", 0)) / 6)) + .5)

def capture(odds, model, players, status, links, now=None):
    now = now or dt.datetime.now(dt.timezone.utc)
    stamp = parse(odds["retrieved_at_utc"])
    if not 0 <= (now - stamp).total_seconds() <= 900:
        return [], "PASS: odds timestamp is future-dated or older than 15 minutes"
    if odds.get("market_id") != 14388 or odds.get("outcome_id") != 14388:
        return [], "PASS: wrong market"
    if model.get("status") != "validated" or model.get("source") != "eligible frozen pregame snapshots with completed graded results":
        return [], "PASS: prospective model not validated"
    if (model.get("train_weeks", 0) < 4 or model.get("test_weeks", 0) < 2
            or model.get("train_players", 0) < 250 or model.get("test_players", 0) < 100
            or model.get("holdout_brier", 1) >= model.get("holdout_baseline_brier", 0)):
        return [], "PASS: insufficient model holdout evidence"
    probs = model.get("probability_by_score_decile")
    supported = model.get("supported_score_deciles")
    if not isinstance(probs, list) or len(probs) != 10 or not isinstance(supported, list) or len(supported) != 10:
        return [], "PASS: incomplete calibration"
    if not links:
        return [], "PASS: no independently verified player/fixture mappings"
    indexed = {p["player_id"]: p for p in players if p.get("player_id")}
    output = []
    used = set()
    for game in odds.get("games", []):
        kickoff = parse(game["fixture_metadata"]["startTime"])
        if now >= kickoff or stamp >= kickoff:
            continue
        fixture = str(game["fixture_id"])
        selections = {p["player_name"]: p["american_odds"] for p in game.get("selections", []) if isinstance(p.get("american_odds"), int)}
        for link in links:
            if link.get("fixture_id") != fixture or link.get("verified") is not True:
                continue
            pid = link.get("player_id")
            p = indexed.get(pid)
            if not p or p.get("availability") != "ROSTER_ACTIVE" or p.get("market") != "ATD":
                continue
            if p.get("team") != link.get("team") or p.get("opp") != link.get("opp"):
                continue
            if int(link.get("season", -1)) != int(status.get("season", -2)) or int(link.get("week", -1)) != int(status.get("week", -2)):
                continue
            name = link.get("sportsbook_player_name")
            price = selections.get(name)
            if not isinstance(price, int) or -100 < price < 100:
                continue
            bucket = score_to_bucket(rank(p))
            prob = probs[bucket]
            if supported[bucket] is not True or not isinstance(prob, (int, float)) or not 0 < prob < 1:
                continue
            implied = 100 / (price + 100) if price > 0 else -price / (-price + 100)
            if prob - implied < .05:
                continue
            key = (fixture, pid)
            if key in used:
                continue
            used.add(key)
            output.append({"season": int(status["season"]), "week": int(status["week"]),
                "player_id": pid, "fixture_id": fixture, "team": p["team"], "opp": p["opp"],
                "captured_at_utc": stamp.isoformat(), "kickoff_utc": kickoff.isoformat(),
                "american_odds": price, "model_probability": prob, "model_status": "validated",
                "identity_verified": True, "market_id": 14388, "outcome_id": 14388,
                "edge": round(prob-implied, 6), "score": rank(p)})
    return sorted(output, key=lambda x: -x["edge"])[:3], ("CAPTURED" if output else "PASS: no verified qualifying value")

def main():
    odds = json.loads((ROOT / "hardrock_anytime_td.json").read_text())
    model = json.loads((ROOT / "probability_model.json").read_text())
    players = json.loads((ROOT / "matchups.json").read_text())
    status = json.loads((ROOT / "status.json").read_text())
    links = json.loads(MAPPINGS.read_text()).get("links", []) if MAPPINGS.exists() else []
    decisions, reason = capture(odds, model, players, status, links)
    now = dt.datetime.now(dt.timezone.utc)
    OUT.mkdir(parents=True, exist_ok=True)
    destination = OUT / (now.strftime("%Y%m%dT%H%M%S%fZ") + ".json")
    document = {"captured_at_utc": now.isoformat(), "status": reason,
                "research_only": True, "decisions": decisions}
    destination.write_text(json.dumps(document, indent=2) + "\n")
    print(reason, "|", len(decisions), "frozen decisions")

if __name__ == "__main__":
    main()
