'use strict';
const assert=require('node:assert/strict'),{update}=require('./spread_prospective_ledger.cjs');
const now=Date.parse('2026-12-01T12:00:00Z'),start='2026-12-01T18:00:00Z';
const model={margin:3,probabilities:[.9,.8,.7,.6,.5,.4,.2],interval80:[-10,16]};
const r={sport:'NFL',game_id:'fixture',version:'v1',home:'H',away:'A',start,captured_at:'2026-12-01T11:00:00Z',source_at:'2026-12-01T10:00:00Z',draws:10000,baseline:model,candidate:{...model,margin:4}};
const first=update({}, {forecasts:[r]},'NFL',now);
assert.equal(first.records.length,1);assert.equal(first.records[0].actual,null);
const second=update(first,{forecasts:[{...r,candidate:{...model,margin:99}}]},'NFL',now);
assert.equal(second.records[0].candidate.margin,4);
const after=Date.parse('2026-12-02T12:00:00Z');
const wrong=update(second,{finals:{fixture:{home:'A',away:'H',home_points:24,away_points:20}}},'NFL',after);
assert.equal(wrong.records[0].actual,null);
const graded=update(wrong,{finals:{fixture:{home:'H',away:'A',home_points:24,away_points:20,start}}},'NFL',after);
assert.equal(graded.summary['NFL|v1'].candidate.margin_mae,0);
assert.equal(graded.summary['NFL|v1'].baseline.margin_mae,1);
assert.equal(first.records[0].actual,null);
assert.throws(()=>update({}, {forecasts:[{...r,captured_at:start}]},'NFL',after),/Invalid pregame/);
assert.throws(()=>update({}, {forecasts:[{...r,candidate:{...model,probabilities:[.1,.2,.3,.4,.5,.6,.7]}}]},'NFL',now),/Invalid pregame/);
assert.equal(update(graded,{finals:{fixture:{home:'H',away:'A',home_points:50,away_points:0}}},'NFL',after).records[0].actual.home,24);
console.log('Immutable spread evidence tests passed');
