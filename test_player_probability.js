'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const model=require('./player_probability.js');
const close=(x,y,e=.0005)=>assert.ok(Math.abs(x-y)<e, x+' differs from '+y);
close(model.normalCDF(0),.5);
close(model.normalCDF(1),.841344746,.0001);
close(model.normalCDF(-1),.158655254,.0001);
const actual=[225,245,257,270,265,280,295,250,260,285,275,240];
const base={market:'PASS',history:actual,projection:267,line:254.5,overOdds:'-115',underOdds:'-115'};
const r=model.review(base);
assert.equal(r.valid,true);
assert.equal(r.sample,actual.length);
assert.ok(r.over>.40&&r.over<.8,'do not manufacture extreme win chances');
close(r.over+r.under+r.push,1);
close(r.push,0,.00001);
close(r.overQuote.implied,115/215);
close(r.noVigOver,.5);
close(r.overSide.ev,r.over*(100/115)-r.under,.00001);
assert.equal(r.play,false);
assert.equal(r.betReady,false);
assert.equal(r.modelCalibrated,false);
assert.match(model.format(r),/EXPERIMENTAL model Over/);
assert.match(model.format(r),/hypothetical ROI/);
assert.match(model.format(r),/NO VERIFIED PLAY/);
const noHistory=model.review({...base,history:[260,265]});
assert.equal(noHistory.valid,false);
assert.equal(noHistory.status,'PASS · PROBABILITY UNAVAILABLE');
assert.equal(noHistory.overSide,null);
const injury=model.review({...base,eligible:false,blockReason:'QUESTIONABLE'});
assert.equal(injury.status,'PASS · PLAYER OR GAME STATUS UNVERIFIED');
assert.equal(injury.candidate,null);
assert.equal(model.review({...base,overOdds:'-90'}).status,'PASS · INVALID ODDS');
assert.equal(model.review({...base,overOdds:'',underOdds:''}).status,'ENTER VEGAS ODDS');
const onlyOver=model.review({...base,underOdds:''});
assert.equal(onlyOver.noVigOver,null);
assert.equal(onlyOver.underSide,null);
const integer=model.review({...base,line:255});
assert.ok(integer.push>0,'whole-line player stats have push probability');
close(integer.over+integer.under+integer.push,1);
const veryFavorable=model.review({market:'PASS',history:[290,310,305,300,298,302,307,294,308,299],projection:310,line:200.5,overOdds:'-110',underOdds:'-110'});
assert.equal(veryFavorable.candidate,'OVER','big well-supported mismatch should create research flag');
assert.equal(veryFavorable.play,false,'even strong uncalibrated candidates never approve bets');
const underValue=model.review({market:'PASS',history:[135,140,145,138,142,150,139,147,143,137],projection:140,line:250.5,overOdds:'-110',underOdds:'-110'});
assert.equal(underValue.candidate,'UNDER','must independently evaluate UNDER');
const short=model.review({market:'PASS',history:[300,305,302,301,297,299],projection:310,line:200.5,overOdds:'-110',underOdds:'-110'});
assert.equal(short.status,'PASS · LIMITED VERIFIED HISTORY');
const longOdds=model.review({market:'PASS',history:[290,310,305,300,298,302,307,294,308,299],projection:310,line:200.5,overOdds:'-250',underOdds:'+190'});
assert.equal(longOdds.candidate,null,'-250 must never be recommended');
assert.equal(model.review({...base,history:[0,0,0,0,0]}).sample,5,'true zero stats are observations');
assert.deepEqual(model.nflHistory({seasonGameStats:[{passYards:0},{passYards:275},{}],playerAppearancesVerified:true},'PASS'),[0,275]);
assert.deepEqual(model.nflHistory({seasonGameStats:[{rushYards:100}],playerAppearancesVerified:false},'RUSH'),[]);
for(const file of ['index.html','nba.html']){
 const html=fs.readFileSync(file,'utf8');
 assert.ok(html.includes('src="./player_probability.js"'),file+' must load probability engine');
 const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(Boolean);
 assert.equal(inline.length,1);
 new vm.Script(inline[0],{filename:file});
 assert.ok(html.includes('CookItUpProbability.review'),file+' must compare odds with observed-game probability');
}
console.log('CoOk It Up model probability, EV, uncertainty, push, and NFL/NBA binding tests passed');
