'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const api=require('./nba_book_compare.js');
const example={name:'Sample Guard',market:'assists',line:8.5,forecast:10.4,
 samples:[...Array(70).fill(11),...Array(10).fill(9.5),...Array(20).fill(7)]};
const result=api.compare({line:'9.5',odds:'-110',samples:example.samples,projection:example.forecast,recommendedLine:example.line});
assert.equal(result.status,'compared');
assert.equal(result.win,.7);
assert.equal(result.push,.1);
assert(Math.abs(result.loss-.2)<1e-10);
assert.match(result.text,/OVER 9.5/);
assert.match(result.text,/Model projection 10.4/);
assert.match(result.text,/70.0% simulated OVER clears/);
assert.match(result.text,/10.0% pushes/);
assert.match(result.text,/77.8%/);
assert.match(result.text,/52.4%/);
assert.match(result.text,/original suggested OVER 8.5 is unchanged/);
assert.match(result.text,/not proof of positive EV/);
assert.equal(api.compare({line:'',odds:''}).status,'awaiting');
assert.equal(api.compare({line:'0',odds:'-110'}).status,'invalid');
assert.equal(api.compare({line:'9.25',odds:'-110'}).status,'invalid');
assert.equal(api.compare({line:'9.5',odds:'-90'}).status,'invalid');
assert.equal(api.compare({line:'9.5',odds:'abc'}).status,'invalid');
assert.equal(api.compare({line:'9.5',odds:''}).status,'unpriced');
assert.match(api.compare({line:'10.5',odds:'+150',projection:11}).text,/40.0%/);
const unverified=api.compare({line:'9.5',odds:'-110',samples:[4,10,11],projection:10});
assert.match(unverified.text,/distribution is unavailable/);
assert(!/simulated OVER clears/.test(unverified.text),'small samples must not produce claimed simulations');
let onInput=null;const doc={addEventListener:(name,fn)=>{if(name==='input')onInput=fn}};
const widget=api.create({document:doc});
const markup=widget.render({...example,name:'<img src=x>'},{expanded:true});
assert.match(markup,/Optional sportsbook comparison/);
assert.match(markup,/data-nba-book-input="line"/);
assert.match(markup,/data-nba-book-input="odds"/);
assert.match(markup,/How this comparison works/);
assert.match(markup,/ open/);
assert(!markup.includes('<img src=x>'),'player names are escaped in HTML');
const id=/data-nba-book-card="([^"]+)"/.exec(markup)[1];
const output={textContent:''};
const panel={dataset:{nbaBookCard:id},querySelector:selector=>selector.includes('="line"')?{value:'9.5'}:selector.includes('="odds"')?{value:'-110'}:output};
const target={dataset:{nbaBookInput:'line'},closest:()=>panel};
assert.equal(typeof onInput,'function');
onInput({target});
assert.match(output.textContent,/70.0% simulated OVER clears/);
assert.match(output.textContent,/52.4%/);
const nba=fs.readFileSync('nba.html','utf8'),auto=fs.readFileSync('nba_auto_alt_ui.js','utf8');
assert(nba.includes('nba_book_compare.js'),'comparison script must load in NBA Edition');
assert(nba.indexOf('nba_book_compare.js')<nba.indexOf('nba_auto_alt_ui.js'),'comparison loads before recommendations');
for(const context of ['nba-best-single','nba-top-three','nba-ticket','nba-slate-legacy']){
 assert(nba.includes("context:'"+context+"'"),'All current NBA recommendation surfaces must expose comparison: '+context);
}
assert(nba.includes('bookComparison:nbaBookComparison'),'automatic Best Props must receive shared comparison');
assert(auto.includes("context:'nba-auto'"),'automatic NBA Best Props must show book comparison');
assert(!nba.includes("First basket scorer</h3>'+nbaBookComparison"),'First Basket is not a stat OVER market');
console.log('NBA sportsbook comparison: line, odds, pushes, unpriced/malformed input, safe DOM updates, and all recommendation surfaces PASS');
