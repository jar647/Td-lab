'use strict';
const assert=require('node:assert/strict');
const ui=require('./nba_simulator_ui.js');
const store=new Map(),storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
const tip='2026-12-10T23:00:00Z',before=Date.parse(tip)-3600000;
const model={id:'immutable-one',home:'Home',away:'Away',date:tip,possessionModel:{teams:{Home:{},Away:{}},pace:98,inputTimes:{games:'2026-12-10T18:00:00Z'}}};
const result={possession:{model:'nba-possession-audit-v3',baseline:{home:110,away:105}},simulated:{home:110,away:105,homeWin:.6,margin:{p10:-10,p90:20},total:{p10:195,p90:235}},market:{homeSpread:-5,total:215},markets:[{key:'homeML',price:-150},{key:'awayML',price:130}]};
assert.equal(ui.capture(result,model,storage,before).saved,true);
const changed={...result,simulated:{...result.simulated,home:140},market:{homeSpread:-15,total:230}};
assert.equal(ui.capture(changed,model,storage,before+1000).existing,true);
const frozen=JSON.parse(storage.getItem(ui.KEY));assert.equal(frozen.length,1);assert.equal(frozen[0].projection.home,110);
const players=(team,total)=>Array.from({length:5},(_,i)=>({team,stats:{PTS:String(i===4?total-40:10)}}));
const feed={generated_at:'2026-12-11T06:00:00Z',games:[{id:model.id,status:'STATUS_FINAL',home:'Home',away:'Away',players:[...players('Home',115),...players('Away',100)]}]};
const graded=ui.grade(feed,storage,Date.parse(tip)+8*3600000);
assert.equal(graded.graded,1);
assert.equal(graded.marketBlend0.mlGames,0,'Unverified moneyline prices cannot be a market baseline');
assert.equal(graded.marketBlend0.games,0,'Unverified spread and total cannot be a market baseline');
assert.equal(graded.ensemble.quotedGames,0);
assert.equal(graded.ensemble.weights[1].ats.gamesWithLean,0);
console.log('NBA immutable first snapshot and verified market gate PASS');
